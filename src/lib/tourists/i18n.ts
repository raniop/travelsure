export type Tr = (he: string, vars?: Record<string, string | number>) => string;

export const makeTr = (lang: UiLang): Tr => (he, vars) => {
  const pair = T[he];
  let out = lang === "he" || !pair ? he : pair[lang === "en" ? 0 : 1];
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
};

export const TrContext = createContext<Tr>(makeTr("he"));
export const useTr = () => useContext(TrContext);
